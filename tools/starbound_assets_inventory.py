def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    entries = []
    total = 0
    roots = [RAW / "vehicles" / "modularmech", RAW / "items" / "generic" / "mechparts"]
    for root in roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(RAW).as_posix()
            entries.append({
                "path": rel,
                "size": path.stat().st_size,
                "sha256": sha256(path),
            })
            total += path.stat().st_size
    refs = {}
    for key, info in REFERENCES.items():
        item = dict(info)
        for field in ("item_path", "config"):
            rel = item.get(field)
            p = RAW / rel if rel else None
            item[field + "_sha256"] = sha256(p) if p and p.exists() else None
        arts = []
        for rel in item.get("art", []) + item.get("art_examples", []) + item.get("paths", []):
            p = RAW / rel
            arts.append({"path": rel, "exists": p.exists(), "sha256": sha256(p) if p.exists() else None,
                         "size": p.stat().st_size if p.exists() else None})
        item["artifacts"] = arts
        refs[key] = item
    inventory = {
        "schema": "starbound-mech-assets/1",
        "generatedUtc": datetime.now(timezone.utc).isoformat(),
        "source": {
            "pak": str(PAK),
            "pakSize": PAK.stat().st_size if PAK.exists() else None,
            "pakSha256": sha256(PAK) if PAK.exists() else None,
            "unpacker": str(UNPACKER),
            "unpackerSha256": sha256(UNPACKER) if UNPACKER.exists() else None,
            "extractedRoot": str(RAW),
            "extractionMethod": "Official asset_unpacker.exe bundled with the local Starbound install; REA open_binary reported unsupported .pak format, so the official tool was used.",
        },
        "totals": {
            "files": len(entries),
            "bytes": total,
        },
        "references": refs,
        "files": entries,
        "licenseBoundary": {
            "owner": "Starbound assets are copyright Chucklefish and are not redistributed by this mod.",
            "localUse": "The extracted files are retained outside the mod source/package for development reference and local comparison only.",
            "release": "Wayfarer's released art is original, generated by tools/art/gen_starbound_style_mech.py; the release source/package must not include these raw Starbound files or derived previews.",
            "verification": "Any future direct asset pack is a separate local-only artifact and must not be uploaded to Steam Workshop without explicit permission.",
        },
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "inventory.json").write_text(json.dumps(inventory, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "README.md").write_text(
        "# Starbound mech asset workspace\n\n"
        "This directory holds raw Starbound files extracted from the user's local install for reference. "
        "They are copyright Chucklefish and must not be redistributed in the Wayfarer Workshop package.\n\n"
        "- `source/raw/` — official asset_unpacker output (read-only reference)\n"
        "- `inventory.json` — file hashes, source pak/unpacker hashes, reference selections\n\n"
        "The released Wayfarer art is original and lives in `src/WayfarerMech/Assets`.\n",
        encoding="utf-8",
    )
    print(f"files={len(entries)} bytes={total} -> {OUT / 'inventory.json'}")


if __name__ == "__main__":
    main()
